<#
.SYNOPSIS
    Builds one Optim engine (Optim_x86.dll or Optim_x64.dll) from the OptimLib
    sources plus the C ABI shim.

.DESCRIPTION
    The toolchain triple decides the output name: an i686 gcc produces
    Optim_x86.dll, an x86_64 gcc produces Optim_x64.dll, and each build gets its
    own scratch folder (_build_x86 / _build_x64). The shim compiles OptimLib's
    own translation units into the same DLL, so no separate library is needed.

    OptimLib needs its BaseMatrixOps submodule and Eigen 3.4+:
      <OptimSource>\include\BaseMatrixOps\include\BaseMatrixOps.hpp must exist
      (see patches\README.md) and -EigenPath must point at an Eigen checkout.

.PARAMETER OptimSource
    Path to the OptimLib checkout (the folder containing include\optim.hpp).

.PARAMETER EigenPath
    Path to Eigen 3.4+ headers (the folder containing the Eigen\ directory).

.PARAMETER Toolchain
    Root of the MinGW-w64 toolchain (the folder containing bin\gcc.exe).
    Use C:\mingw32 for x86 and ..\_toolchains\w64devkit for x64.

.PARAMETER OutputDir
    Where the engine is written. Defaults to this folder.
#>
param(
    [Parameter(Mandatory = $true)][string]$OptimSource,
    [Parameter(Mandatory = $true)][string]$EigenPath,
    [string]$Toolchain = "C:\mingw32",
    [string]$OutputDir = ""
)

$ErrorActionPreference = "Stop"

$here = $PSScriptRoot
if ($OutputDir -eq "") { $OutputDir = $here }

# Absolute paths only: relative toolchain paths confuse nothing here, but the
# generated optim_all.cpp embeds absolute include paths, so normalise up front.
$OptimSource = (Resolve-Path $OptimSource).Path
$EigenPath = (Resolve-Path $EigenPath).Path
$Toolchain = (Resolve-Path $Toolchain).Path

$gxx = Join-Path $Toolchain "bin\g++.exe"
if (-not (Test-Path $gxx)) {
    throw "g++ not found at $gxx (pass -Toolchain <root containing bin\g++.exe>)"
}

$includeDir = Join-Path $OptimSource "include"
if (-not (Test-Path (Join-Path $includeDir "optim.hpp"))) {
    throw "optim.hpp not found under $includeDir - is -OptimSource the OptimLib checkout?"
}
$bmo = Join-Path $includeDir "BaseMatrixOps\include\BaseMatrixOps.hpp"
if (-not (Test-Path $bmo)) {
    throw "BaseMatrixOps is missing ($bmo). OptimLib needs its submodule; see patches\README.md."
}
if (-not (Test-Path (Join-Path $EigenPath "Eigen\Dense"))) {
    throw "Eigen headers not found under $EigenPath (expected Eigen\Dense)"
}

$triple = (& $gxx -dumpmachine).Trim()
if ($triple -match "x86_64|amd64") {
    $engineName = "Optim_x64.dll"
    $buildDir = Join-Path $here "_build_x64"
}
elseif ($triple -match "i686|i386") {
    $engineName = "Optim_x86.dll"
    $buildDir = Join-Path $here "_build_x86"
}
else {
    throw "Unsupported toolchain triple '$triple' (need i686 or x86_64)"
}

Write-Host "Toolchain : $Toolchain ($triple)"
Write-Host "OptimLib  : $OptimSource"
Write-Host "Eigen     : $EigenPath"
Write-Host "Output    : $(Join-Path $OutputDir $engineName)"

New-Item -ItemType Directory -Force -Path $buildDir | Out-Null

# One translation unit for the whole library: OptimLib declares in headers and
# defines in src\*.cpp; including them all once keeps the build short and makes
# the template-heavy Eigen code compile a single time instead of thirteen.
$all = Join-Path $buildDir "optim_all.cpp"
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// generated by build-native.ps1 - do not edit")
Get-ChildItem (Join-Path $OptimSource "src") -Recurse -Filter *.cpp |
    Sort-Object FullName |
    ForEach-Object {
        [void]$sb.AppendLine('#include "' + $_.FullName.Replace('\', '/') + '"')
    }
Set-Content -LiteralPath $all -Value $sb.ToString() -Encoding ASCII

$shim = Join-Path $here "optim_shim.cpp"
$out = Join-Path $OutputDir $engineName
if (Test-Path $out) { Remove-Item -Force $out }

$gccArgs = @(
    "-std=c++17", "-O2", "-shared",
    "-DOPTIM_ENABLE_EIGEN_WRAPPERS", "-DOPTIM_DONT_USE_OPENMP",
    "-I", $includeDir,
    "-I", $EigenPath,
    $shim, $all,
    "-o", $out,
    "-static", "-static-libgcc", "-static-libstdc++",
    "-Wl,--no-undefined"
)

Write-Host "`nCompiling $engineName ..."
& $gxx @gccArgs
if ($LASTEXITCODE -ne 0) { throw "g++ failed with exit code $LASTEXITCODE" }

$item = Get-Item $out
Write-Host ("Built {0} ({1} bytes)" -f $item.Name, $item.Length)
